// Tests of tools/resume-claims.mjs: number extraction, the resume difference rows, bullet rendering from approved
// claims only, and the CLI end to end on the resume fixture (--text, so pdftotext is not needed).
import { test } from 'node:test';
import assert from 'node:assert/strict';
import { execFile } from 'node:child_process';
import { mkdtemp, readFile, readdir, rm, writeFile } from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { extractNumbers, diffResume, renderBullets, sections, contactLike, TemplateError } from '../resume-claims.mjs';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const CLI = path.join(HERE, '..', 'resume-claims.mjs');
const FIXTURE = path.join(HERE, 'fixtures', 'resume');
const doc = JSON.parse(await readFile(path.join(FIXTURE, 'claims.json'), 'utf8'));
const byId = new Map(doc.claims.map((c) => [c.id, c]));
const of = (project) => doc.claims.filter((c) => c.project === project);

function run(args, cwd) {
  return new Promise((resolve) => {
    execFile(process.execPath, [CLI, ...args], { cwd }, (err, stdout, stderr) => resolve({ code: err ? err.code : 0, stdout, stderr }));
  });
}
// A temp directory outside any git work tree, with the fixture claims and the given templates.
async function workdir(templates) {
  const dir = await mkdtemp(path.join(os.tmpdir(), 'resume-claims-'));
  await writeFile(path.join(dir, 'templates.md'), templates ?? await readFile(path.join(FIXTURE, 'templates.md'), 'utf8'));
  return dir;
}
const cliArgs = (dir) => ['--claims', path.join(FIXTURE, 'claims.json'), '--templates', path.join(dir, 'templates.md'),
  '--text', path.join(FIXTURE, 'resume.txt'), '--out', path.join(dir, 'bullets.md'), '--report', path.join(dir, 'report.md')];

// ---------- extractNumbers ----------
test('extractNumbers reads approximate, range, thousands and SI numbers with their nouns', () => {
  const got = extractNumbers('scaling to 1M keys at ~134 bytes per key; 54 tests; failing 6-28 of 1,000 runs; 100 concurrent clients');
  assert.deepEqual(got.map((n) => [n.text, n.noun, n.unit]), [
    ['1M', 'keys', 'keys'], ['~134', 'bytes per key', 'bytes'], ['54', 'tests', 'tests'],
    ['6-28', 'of 1,000 runs', 'runs'], ['1,000', 'runs', 'runs'], ['100', 'concurrent clients', 'connections'],
  ]);
  assert.equal(got[0].value, 1e6);
  assert.equal(got[1].value, 134);
  assert.deepEqual(got[3].range, { low: 6, high: 28 });
  assert.equal(got[4].value, 1000);
});

test('extractNumbers skips digits glued to a word, a version or a flag', () => {
  assert.deepEqual(extractNumbers('C++20, WSL2, v1.2 and -O3 builds').map((n) => n.text), []);
});

test('extractNumbers joins a number and its noun wrapped across lines', () => {
  assert.deepEqual(extractNumbers('at ~134\n\nbytes per key').map((n) => [n.text, n.unit]), [['~134', 'bytes']]);
});

// ---------- diffResume ----------
test('diffResume: matches, differs and no claim, by unit, approved claims only', () => {
  const rows = diffResume('� at ~134 bytes per key and 1M keys � 60 tests', of('ratelimit-cpp'));
  assert.deepEqual(rows.map((r) => [r.number, r.status, r.claims]), [
    ['~134 bytes per key', 'matches', ['rl.fixture.memory.k1000000']],
    ['1M keys', 'no claim', []],
    // rl.fixture.proposed (60 tests) is not approved, so 60 differs from the approved 54.
    ['60 tests', 'differs', ['rl.fixture.tests']],
  ]);
  assert.equal(rows[0].claimValue, '134.2 bytes');
  assert.equal(rows[2].claimValue, '54 tests');
  assert.equal(rows[0].context, 'at ~134 bytes per key and 1M keys');
});

test('diffResume lists "no measurable ..." as wording', () => {
  const rows = diffResume('confirming no measurable slowdown on /quality', of('image-quality-gate'));
  assert.deepEqual(rows.map((r) => [r.number, r.status]), [['no measurable slowdown', 'wording']]);
});

// ---------- sections ----------
test('sections finds the three project sections and skips heading lines and other entries', async () => {
  const text = await readFile(path.join(FIXTURE, 'resume.txt'), 'utf8'), found = sections(text);
  assert.deepEqual(found.map((s) => s.project), ['ratelimit-cpp', 'image-quality-gate', 'key-value-storage']);
  assert.ok(found.every((s) => s.body !== null));
  assert.doesNotMatch(found[0].body, /2025|2\.8M|ACTIVITIES/);
  assert.doesNotMatch(found[2].body, /500\+/);
});

// ---------- renderBullets ----------
test('renderBullets fills every placeholder field from approved claims', () => {
  const out = renderBullets('<!-- guidance -->\n- {{claim:rl.fixture.memory.k1000000}} ({{claim:rl.fixture.memory.k1000000#spread}}, '
    + '{{claim:rl.fixture.memory.k1000000#n}}, {{claim:rl.fixture.memory.k1000000#environment}})\n', byId, { environments: doc.environments });
  assert.match(out, /^<!-- Generated by tools\/resume-claims\.mjs/);
  assert.match(out, /^- 134\.2 \(134\.2–134\.2, 10 runs, Ubuntu on WSL2\)$/m);
  assert.doesNotMatch(out, /guidance|\{\{/);
});

test('renderBullets throws naming every proposed, unknown or unrenderable id', () => {
  assert.throws(() => renderBullets('{{claim:rl.fixture.proposed}} {{claim:no.such.id}} {{claim:rl.fixture.tests#spread}} {{claim:rl.fixture.tests#bogus}}', byId),
    (err) => err instanceof TemplateError && err.problems.length === 4
      && /rl\.fixture\.proposed: has status proposed/.test(err.message) && /no\.such\.id: not in/.test(err.message)
      && /rl\.fixture\.tests: has no display\.spread/.test(err.message) && /unknown field "bogus"/.test(err.message));
});

test('renderBullets rejects a malformed placeholder', () => {
  assert.throws(() => renderBullets('{{claim rl.fixture.tests}}', byId), TemplateError);
});

test('contactLike flags an e-mail, a long digit run and a phone shape', () => {
  assert.equal(contactLike('jane@example.com'), true);
  assert.equal(contactLike('call 5550100199'), true);
  assert.equal(contactLike('(555) 010-0199'), true);
  assert.equal(contactLike('10,711 commands per second, 153.3M calls/s, 1,000,000 keys'), false);
});

// ---------- CLI ----------
test('CLI on the fixture writes bullets and a report with the expected rows', async () => {
  const dir = await workdir();
  try {
    const r = await run(cliArgs(dir), dir);
    assert.equal(r.code, 0, r.stdout + r.stderr);
    assert.match(r.stdout, /wrote .*bullets\.md/);
    assert.match(r.stdout, /wrote .*report\.md \(local only\)/);
    const rep = await readFile(path.join(dir, 'report.md'), 'utf8');
    assert.equal((rep.match(/^## /gm) ?? []).length, 3);
    for (const row of [
      /\| ~134 bytes per key \| matches \| `rl\.fixture\.memory\.k1000000` \| 134\.2 bytes \|/,
      /\| 54 tests \| matches \| `rl\.fixture\.tests` \| 54 tests \|/,
      /\| 6-28 of 1,000 runs \| no claim \| {2}\| {2}\|/,
      /\| 1,000 runs \| no claim \|/,
      /\| no measurable slowdown \| wording \|/,
      /\| 130 tests \| matches \| `iqg\.fixture\.tests` \|/,
      /\| 100 concurrent clients \| matches \| `kv\.fixture\.max_connections` \| 100 connections \|/,
      /\| 54 tests \| differs \| `kv\.fixture\.tests` \| 50 tests \|/,
    ]) assert.match(rep, row);
    assert.doesNotMatch(rep, /2\.8M|500\+|2025/);
    const bullets = await readFile(path.join(dir, 'bullets.md'), 'utf8');
    assert.match(bullets, /Held memory to 134\.2 heap bytes per key \(Ubuntu on WSL2, median of 10 runs\); 54 tests pass\./);
    assert.ok(!bullets.includes('@'), 'no @ in the bullets');
    assert.doesNotMatch(bullets, /\d{7,}/);
  } finally {
    await rm(dir, { recursive: true, force: true });
  }
});

test('CLI exits 1 naming a proposed id and writes nothing', async () => {
  const dir = await workdir('## Rate Limiter\n\n- {{claim:rl.fixture.proposed}} pass.\n');
  try {
    const r = await run(cliArgs(dir), dir);
    assert.equal(r.code, 1, r.stdout);
    assert.match(r.stdout, /rl\.fixture\.proposed: has status proposed/);
    assert.deepEqual((await readdir(dir)).sort(), ['templates.md']);
  } finally {
    await rm(dir, { recursive: true, force: true });
  }
});

test('CLI never writes under static/', async () => {
  const dir = await workdir();
  try {
    for (const flag of ['--out', '--report']) {
      const args = cliArgs(dir), i = args.indexOf(flag);
      args[i + 1] = path.join('static', 'x.md');
      const r = await run(args, dir);
      assert.equal(r.code, 2, r.stdout);
      assert.match(r.stdout, /under static\/; this tool never writes there/);
    }
    assert.deepEqual((await readdir(dir)).sort(), ['templates.md']);
  } finally {
    await rm(dir, { recursive: true, force: true });
  }
});

test('CLI refuses a report path that git tracks', async () => {
  const dir = await workdir();
  try {
    const args = cliArgs(dir), i = args.indexOf('--report');
    // tools/ is inside the portfolio work tree and not ignored.
    args[i + 1] = path.join(HERE, 'resume-report-must-not-exist.md');
    const r = await run(args, dir);
    assert.equal(r.code, 2, r.stdout);
    assert.match(r.stdout, /is not git-ignored/);
    await assert.rejects(readFile(args[i + 1]));
  } finally {
    await rm(dir, { recursive: true, force: true });
  }
});

test('CLI rejects --text together with --pdf', async () => {
  const r = await run(['--text', 'a.txt', '--pdf', 'b.pdf'], os.tmpdir());
  assert.equal(r.code, 2);
  assert.match(r.stdout, /pick one input/);
});
